from __future__ import annotations

from fastapi import APIRouter, HTTPException, Request
from pydantic import BaseModel, Field
from sqlalchemy import select

from app.core.models import Offer
from app.knowledge import hardware as hw
from app.planner import suppliers
from app.planner.shopping import _gross, load_options

router = APIRouter(prefix="/api/encyclopedia")


def _text(it: dict) -> str:
    cat = hw.CAT_BY_ID[it["category"]]
    return " ".join([it["name"], it["summary"], cat["title"], " ".join(m["name"] for m in it["models"]), it.get("notes", ""),
                     " ".join(it["interface"])]).lower()


@router.get("")
def index(q: str | None = None, category: str | None = None):
    terms = (q or "").lower().split()
    items = [i for i in hw.ITEMS if (not category or i["category"] == category) and all(t in _text(i) for t in terms)]
    return {"categories": [{"id": c["id"], "title": c["title"], "count": sum(1 for i in hw.ITEMS if i["category"] == c["id"])} for c in hw.CATEGORIES],
            "items": [{"id": i["id"], "name": i["name"], "summary": i["summary"], "category": i["category"],
                       "interface": [hw.IFACE_TEXT.get(x, x) for x in i["interface"]], "driver": i["driver"]} for i in items]}


@router.get("/{item_id}")
def item_page(item_id: str, request: Request):
    p = hw.page(item_id)
    if p is None:
        raise HTTPException(404, "unknown hardware item")
    db = request.app.state.db
    vat = load_options(db).vat_rate
    names = {s["id"]: s["name"] for s in suppliers.SUPPLIERS}
    with db.session() as s:
        offers = s.scalars(select(Offer).where(Offer.item_id.in_(p["bom_ids"]))).all() if p["bom_ids"] else []
    p["purchase"] = {
        "offers": [{"supplier": names.get(o.supplier_id, o.supplier_id), "product": o.product_name, "price_ron_incl_vat": round(_gross(o, vat), 2),
                    "status": o.status, "url": o.url, "availability": o.availability, "checked_at": o.checked_at} for o in offers],
        "note": ("Prices and links appear here only when an offer has been recorded (Shopping page). "
                 "None are generated by the application, so a missing price means 'not researched'.")}
    p["compatibility"] = hw.compat(hw.ITEM_BY_ID[item_id])
    with db.session() as s:
        from app.core.models import Actuator, Sensor
        used = []
        if p["driver"]:
            used += [x.id for x in s.scalars(select(Sensor).where(Sensor.driver == p["driver"]))]
            used += [x.id for x in s.scalars(select(Actuator).where(Actuator.driver == p["driver"]))]
    p["used_in_your_system"] = used
    return p


@router.get("/{item_id}/compatibility")
def item_compat(item_id: str):
    it = hw.ITEM_BY_ID.get(item_id)
    if it is None:
        raise HTTPException(404, "unknown hardware item")
    return hw.compat(it)


class CustomIn(BaseModel):
    interface: list[str] = Field(min_length=1)
    supply: str = ""
    external_power: bool = False
    needs_adc: bool = False
    esp32: str = "yes"


@router.post("/compatibility/check")
def custom_check(body: CustomIn):
    bad = [i for i in body.interface if i not in hw.IFACE_TEXT]
    if bad:
        raise HTTPException(422, f"unknown interface(s) {bad}; choose from {sorted(hw.IFACE_TEXT)}")
    return hw.custom_compat(body.interface, body.supply, body.external_power, body.needs_adc, body.esp32)
